#!/usr/bin/env bash
# Build patched libptts_ffi.so (with Cilla Lite bos_before_voice remap, raw-chunk synthesis,
# and on-device MimiEnc voice cloning) for Android arm64-v8a and x86_64.
#
# Output: app/src/main/jniLibs/{arm64-v8a,x86_64}/libptts_ffi.so, plus the symbol manifest
# app/src/main/jniLibs/ptts-ffi.symbols that `app/build.gradle.kts` checks the libraries against.
#
# `--symbols-only` writes just the manifest, which is what CI needs after a cache hit.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"

symbols() {
  local manifest="$REPO_ROOT/app/src/main/jniLibs/ptts-ffi.symbols"
  mkdir -p "$(dirname "$manifest")"
  {
    echo "# Generated by native/build-ptts-ffi.sh; do not edit."
    echo "# Symbols this app calls. Each must be exported by both ABIs."
    for symbol in ptts_new ptts_speak ptts_speak_raw ptts_count_tokens \
      ptts_add_voice_file ptts_supports_voice_cloning ptts_clone_voice_to_file \
      ptts_clone_voices_to_dir ptts_strings_free; do
      echo "$symbol"
    done
  } > "$manifest"
  echo "Wrote $manifest"
}

if [[ "${1:-}" == "--symbols-only" ]]; then
  symbols
  exit 0
fi

NATIVE_DIR="$REPO_ROOT/native"
XN_PTTS_REPO="https://github.com/gradium-ai/xn-ptts.git"
XN_PTTS_COMMIT="45432e010d37f3d8aede95022718d7b0c3da4aca"
WORK_DIR="${XN_PTTS_WORK_DIR:-$NATIVE_DIR/.work/xn-ptts}"
OUT_DIR="${OUT_DIR:-$REPO_ROOT/app/src/main/jniLibs}"

if [ -z "${ANDROID_NDK_HOME:-}" ]; then
  SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-/usr/local/lib/android/sdk}}"
  if [ -d "$SDK/ndk" ]; then
    LATEST_NDK="$(ls -1 "$SDK/ndk" | sort -V | tail -n 1 || true)"
    if [ -n "$LATEST_NDK" ]; then
      export ANDROID_NDK_HOME="$SDK/ndk/$LATEST_NDK"
    fi
  elif [ -d "$SDK/ndk-bundle" ]; then
    export ANDROID_NDK_HOME="$SDK/ndk-bundle"
  fi
fi

if [ -z "${ANDROID_NDK_HOME:-}" ] || [ ! -d "$ANDROID_NDK_HOME" ]; then
  echo "ANDROID_NDK_HOME is not set and no Android NDK was found." >&2
  exit 1
fi
echo "Using ANDROID_NDK_HOME=$ANDROID_NDK_HOME"

export PATH="$HOME/.cargo/bin:$PATH"
if ! command -v cargo-ndk >/dev/null 2>&1; then
  echo "Installing cargo-ndk..."
  cargo install cargo-ndk --locked
fi

rustup target add aarch64-linux-android x86_64-linux-android >/dev/null

mkdir -p "$(dirname "$WORK_DIR")"
if [ ! -d "$WORK_DIR/.git" ]; then
  rm -rf "$WORK_DIR"
  mkdir -p "$WORK_DIR"
  git -C "$WORK_DIR" init -q
  git -C "$WORK_DIR" remote add origin "$XN_PTTS_REPO"
fi

git -C "$WORK_DIR" fetch --depth 1 origin "$XN_PTTS_COMMIT"
git -C "$WORK_DIR" checkout -q --force FETCH_HEAD
git -C "$WORK_DIR" clean -fdx -e target
git -C "$WORK_DIR" apply "$NATIVE_DIR/xn-ptts.patch"

ARM64_FEATURES="${ARM64_FEATURES-+dotprod,+fp16}"
COMMON="-C strip=symbols -C link-arg=-Wl,-z,max-page-size=16384"
export CARGO_TARGET_AARCH64_LINUX_ANDROID_RUSTFLAGS="$COMMON -C target-cpu=generic${ARM64_FEATURES:+ -C target-feature=$ARM64_FEATURES}"
export CARGO_TARGET_X86_64_LINUX_ANDROID_RUSTFLAGS="$COMMON -C target-cpu=x86-64"
unset RUSTFLAGS CARGO_ENCODED_RUSTFLAGS

STAGE_DIR="$NATIVE_DIR/.work/jniLibs"
rm -rf "$STAGE_DIR"
mkdir -p "$STAGE_DIR"

(
  cd "$WORK_DIR"
  cargo ndk -t arm64-v8a -t x86_64 -o "$STAGE_DIR" build --release -p ptts-ffi
)

mkdir -p "$OUT_DIR/arm64-v8a" "$OUT_DIR/x86_64"
cp "$STAGE_DIR/arm64-v8a/libptts_ffi.so" "$OUT_DIR/arm64-v8a/libptts_ffi.so"
cp "$STAGE_DIR/x86_64/libptts_ffi.so" "$OUT_DIR/x86_64/libptts_ffi.so"

du -sh "$OUT_DIR/arm64-v8a/libptts_ffi.so" "$OUT_DIR/x86_64/libptts_ffi.so"

# A generated record of what the app needs from these libraries, so a stale `.so` is a build
# error rather than a mystery at runtime (see `app/build.gradle.kts`).
symbols
python3 "$NATIVE_DIR/check-ptts-ffi.py" "$REPO_ROOT"
